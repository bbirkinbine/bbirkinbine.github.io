const portrait = document.querySelector("[data-ansi-portrait]");

if (portrait) {
  const fragment = document.createDocumentFragment();

  for (let y = 0; y < portraitRows.length; y += 2) {
    const top = portraitRows[y];
    const bottom = portraitRows[y + 1];
    const row = document.createElement("span");
    row.className = "ansi-row";

    let runStart = 0;
    let runTop = top[0];
    let runBottom = bottom[0];

    const appendRun = (end) => {
      const cells = document.createElement("span");
      cells.className = `ansi-f${runTop} ansi-b${runBottom}`;
      cells.textContent = "▀".repeat(end - runStart);
      row.append(cells);
    };

    for (let x = 1; x <= top.length; x += 1) {
      if (x === top.length || top[x] !== runTop || bottom[x] !== runBottom) {
        appendRun(x);
        runStart = x;
        runTop = top[x];
        runBottom = bottom[x];
      }
    }

    fragment.append(row);
  }

  portrait.append(fragment);
}
