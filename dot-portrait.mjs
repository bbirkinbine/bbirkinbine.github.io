const decodeRow = (encoded) => {
  const bytes = Uint8Array.from(atob(encoded), (character) => character.charCodeAt(0));
  const levels = new Uint8Array(portraitColumns);

  bytes.forEach((byte, index) => {
    levels[index * 2] = byte >> 4;
    levels[index * 2 + 1] = byte & 0x0f;
  });

  return levels;
};

const portraitLevels = portraitRows.map(decodeRow);
const canvas = document.querySelector("[data-dot-portrait]");

if (canvas) {
  const context = canvas.getContext("2d");
  const root = document.documentElement;
  const printMode = window.matchMedia("print");
  let animationFrame;

  const render = () => {
    const width = canvas.getBoundingClientRect().width;
    if (!width) return;

    const pitch = width / portraitColumns;
    const height = pitch * portraitRowCount;
    const pixelRatio = Math.min(window.devicePixelRatio || 1, 2);
    const rootStyles = getComputedStyle(root);

    canvas.width = Math.round(width * pixelRatio);
    canvas.height = Math.round(height * pixelRatio);
    context.setTransform(pixelRatio, 0, 0, pixelRatio, 0, 0);
    context.clearRect(0, 0, width, height);
    context.fillStyle = rootStyles.getPropertyValue("--portrait-dot").trim();
    context.beginPath();

    portraitLevels.forEach((row, y) => {
      row.forEach((level, x) => {
        if (level === 0) return;

        const normalized = (level - 1) / 14;
        const strength = normalized ** 0.95;
        const radius = pitch * (0.08 + 0.38 * strength);
        const centerX = (x + 0.5) * pitch;
        const centerY = (y + 0.5) * pitch;

        context.moveTo(centerX + radius, centerY);
        context.arc(centerX, centerY, radius, 0, Math.PI * 2);
      });
    });

    context.fill();
  };

  const scheduleRender = () => {
    cancelAnimationFrame(animationFrame);
    animationFrame = requestAnimationFrame(render);
  };

  new ResizeObserver(scheduleRender).observe(canvas);
  new MutationObserver(scheduleRender).observe(root, {
    attributes: true,
    attributeFilter: ["data-style"],
  });
  printMode.addEventListener("change", scheduleRender);
  scheduleRender();
}
